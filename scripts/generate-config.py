"""Generate a PlainRoute config for one OpenAI-compatible upstream with N key slots.

The model list is not guessed: it comes from the live model endpoint, and falls back to a
snapshot file when that endpoint is unreachable.

The generated file is the config a gateway runs on, and a config a gateway runs on holds the keys, so
it is a secret. This script writes a placeholder in each key slot and never reads, accepts or prints
a key: a real key gets in only when a person types it into the file, which is the point. A file a
reader can read is a file a reader can check, and a script that could write a key is a script that
could commit one.

Each route is named after a model, and every key slot is a target that carries that model name.

Usage:
  python3 scripts/generate-config.py --keys 4 --max-active 8 --out config.yaml
  python3 scripts/generate-config.py --models models.json        # snapshot, no network
  python3 scripts/generate-config.py --base-url https://api.example.com/v1
  python3 scripts/generate-config.py --max-request-bytes 33554432 --max-response-bytes 67108864
      --cooldown-max 30s --cooldown-503 0s

The numbers above are the defaults this script writes, and they are the recommendation for a
coding-agent workload rather than the library default: a coding agent that carries a screenshot
sends a body in the tens of megabytes. They are parameters because the right number depends on the
workload, and a script that hardcodes one person's workload is a config people edit by hand after.

The target names are stable (slot numbers), so a reload keeps the cooldown of a
target that is still configured.
"""

import argparse
import json
import os
import sys
import urllib.error
import urllib.request

YAML = """\
# Generated by scripts/generate-config.py - do not edit by hand.
# Each REPLACE_ME_ACCOUNT_n is a slot to fill in with one account's key. The file you fill in is a
# secret: it needs 600 permissions, it is gitignored, and it is the file the gateway runs on.
# Source: {source}, {count} routes x {keys} key slots = {targets} targets.

server:
  listen: "{listen}"
  read_header_timeout: 10s
  read_timeout: 30s
  # 0 keeps a streaming response from being cut off by an ordinary request timeout.
  write_timeout: 0s
  idle_timeout: 120s
  shutdown_grace: 30s
  # What a coding agent needs, and what the CLI parameters set. The library default is smaller, so
  # a file made by this script says the number it wrote instead of leaving a reader to guess which
  # default it is looking at. 0 or absent in the config means the library default.
  max_request_bytes: {max_request_bytes}
  max_response_bytes: {max_response_bytes}
  max_header_bytes: 1048576

timeouts:
  connect: 10s
  response_header: {response_header}s
  stream_idle: {stream_idle}s
  request: 0s

routing:
  # Ties keep the order they appear in this file, so a choice is reproducible.
  #
  # Measured, not assumed: least_active picks the target with the fewest requests in
  # flight, so sequential traffic (nothing overlapping) stays on one slot, while round_robin
  # spreads it. When the limit is per key, spreading is what you want; when it is per
  # connection pool, least_active is closer. This run measured 12 sequential requests:
  # round_robin 3/3/3/3, least_active 12/0/0/0.
  strategy: {strategy}
  cooldown:
    status:
      429: {cooldown_429}
      401: 60s
      403: 60s
      # 0 means no window: a 503 normally says the service behind the key is temporarily
      # unavailable, not that this key is broken. PlainRoute does not count consecutive
      # failures, so a window here would hold a working key out for a failure that may not
      # belong to it. Write a window here only when you know your provider means the key, which is
      # what --cooldown-503 is for.
      503: {cooldown_503}
    max: {cooldown_max}
    timeout: 0s

retry:
  enabled: false
  max_attempts: 1

fallbacks:
  enabled: false
  max_hops: 1

headers:
  mode: deny
  deny: [Cookie, X-Forwarded-For]
  forward_request_id: true

logging:
  format: json
  level: info

metrics:
  enabled: true
  path: /metrics

routes:
{routes}
"""


def fetch_models(base_url: str, timeout: int) -> list[str]:
    url = base_url.rstrip("/") + "/models"
    with urllib.request.urlopen(url, timeout=timeout) as response:
        data = json.load(response)
    ids = [entry["id"] for entry in data.get("data", []) if entry.get("id")]
    return sorted(ids)


def load_snapshot(path: str) -> list[str]:
    with open(path) as handle:
        ids = json.load(handle)
    return sorted(ids)


def block_quote(value: str) -> str:
    """Quote a model id so YAML reads it as a string. An id such as `qwen3:8b` needs quoting
    because a colon followed by a space would otherwise read as a mapping."""
    return '"' + value.replace('"', '\\"') + '"'


def build_routes(models: list[str], key_slots: int, base_url: str, max_active: int) -> str:
    lines = []
    for model in models:
        lines.append(f"  {block_quote(model)}:")
        lines.append("    targets:")
        for slot in range(1, key_slots + 1):
            lines.append(f"      - name: slot-{slot}")
            # The model belongs to the target, not to the route, so a key slot that serves a
            # different model is one field away from being a different target.
            lines.append(f"        model: {block_quote(model)}")
            lines.append(f"        base_url: {base_url}")
            # A placeholder, and only a placeholder. Nothing in this script can put a real key here.
            lines.append(f"        api_key: REPLACE_ME_ACCOUNT_{slot}")
            lines.append(f"        max_active: {max_active}")
        # A blank line between routes keeps a 128-target file readable in an editor.
        lines.append("")
    return "\n".join(lines).rstrip()


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate a PlainRoute YAML config.")
    parser.add_argument("--base-url", default="https://api.example.com/v1")
    parser.add_argument("--keys", type=int, default=4)
    parser.add_argument("--max-active", type=int, default=8)
    parser.add_argument("--models", help="snapshot JSON file used when the live endpoint is unreachable")
    parser.add_argument("--out", default="config.yaml")
    parser.add_argument("--listen", default=":8080")
    parser.add_argument("--strategy", default="least_active", choices=["least_active", "round_robin"])
    parser.add_argument("--response-header", type=int, default=120)
    parser.add_argument("--stream-idle", type=int, default=300)
    parser.add_argument("--max-request-bytes", type=int, default=33554432,
                        help="32 MiB, the size a coding-agent body with a screenshot in it needs; 0 means the library default")
    parser.add_argument("--max-response-bytes", type=int, default=67108864,
                        help="64 MiB; 0 means the library default")
    parser.add_argument("--cooldown-429", default="10s",
                        help="the prior for the silent case, used when the upstream sent no usable Retry-After")
    parser.add_argument("--cooldown-503", default="0s",
                        help="0 means no window, which is what a 503 normally deserves; write a window when your provider means the key")
    parser.add_argument("--cooldown-max", default="30s",
                        help="the clamp on a value the upstream sent; 0 turns the clamp off, and the library default is 15m")
    parser.add_argument("--timeout", type=int, default=20, help="seconds to wait for the model list")
    args = parser.parse_args()

    source = "live model endpoint"
    models = []
    error = None
    try:
        models = fetch_models(args.base_url, args.timeout)
    except (urllib.error.URLError, OSError, json.JSONDecodeError, KeyError) as exc:
        error = exc

    if not models:
        # An endpoint that answers with an empty list is not a model list. The snapshot is
        # the fallback in both cases: unreachable, or reachable but empty.
        if not args.models:
            print(f"the model endpoint gave no models ({error or 'empty list'}) and no snapshot was given", file=sys.stderr)
            return 1
        models = load_snapshot(args.models)
        source = f"snapshot {args.models} (live endpoint gave nothing: {error or 'empty list'})"

    text = YAML.format(
        source=source,
        count=len(models),
        keys=args.keys,
        targets=len(models) * args.keys,
        listen=args.listen,
        strategy=args.strategy,
        response_header=args.response_header,
        stream_idle=args.stream_idle,
        max_request_bytes=args.max_request_bytes,
        max_response_bytes=args.max_response_bytes,
        cooldown_429=args.cooldown_429,
        cooldown_503=args.cooldown_503,
        cooldown_max=args.cooldown_max,
        routes=build_routes(models, args.keys, args.base_url, args.max_active),
    )

    with open(args.out, "w") as handle:
        handle.write(text)

    print(f"{len(models)} models x {args.keys} key slots = {len(models) * args.keys} targets -> {args.out}")
    print(f"source: {source}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
